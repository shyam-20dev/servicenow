REQUEST_GROUPS = {"IT": "IT Service Desk", "HR": "HR Operations",
                  "Finance": "Finance Shared Services", "Facilities": "Facilities Management"}


def _ts(hours_ago: int) -> str:
    return (datetime.now(timezone.utc) - timedelta(hours=hours_ago)).strftime("%Y-%m-%d %H:%M:%S")


def seed_if_empty() -> None:
    with get_conn() as conn:
        if conn.execute("SELECT COUNT(*) FROM incidents").fetchone()[0] == 0:
            for short, desc, cat, imp, urg, status, h in SAMPLE_INCIDENTS:
                group = GROUP_FOR_CATEGORY[cat]
                cur = conn.execute(
                    "INSERT INTO incidents (short_description, description, category, impact, urgency, priority, "
                    "status, assignment_group, assigned_to, reporter, ai_summary, ai_steps, ai_resolution, "
                    "ai_source, ai_note, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                    (short, desc, cat, imp, urg, calculate_priority(imp, urg), status, group,
                     TECHNICIAN_FOR_GROUP[group], "demo.employee", short,
                     json.dumps(["Sample data - create a new incident to see live AI analysis."]),
                     "Sample data - no AI analysis was run for this record.",
                     "sample data", "Seeded demo record; not generated by an LLM.", _ts(h), _ts(h)))
                conn.execute("UPDATE incidents SET number=? WHERE id=?", (f"INC{1000000 + cur.lastrowid}", cur.lastrowid))
        if conn.execute("SELECT COUNT(*) FROM service_requests").fetchone()[0] == 0:
            for dept, rtype, title, desc, prio, status, h in SAMPLE_REQUESTS:
                cur = conn.execute(
                    "INSERT INTO service_requests (department, request_type, title, description, requester, priority, "
                    "status, assignment_group, created_at, updated_at) VALUES (?,?,?,?,?,?,?,?,?,?)",
                    (dept, rtype, title, desc, "demo.employee", prio, status, REQUEST_GROUPS[dept], _ts(h), _ts(h)))
                conn.execute("UPDATE service_requests SET number=? WHERE id=?", (f"REQ{2000000 + cur.lastrowid}", cur.lastrowid))
